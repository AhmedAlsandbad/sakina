-- Sakina Quran Web Push backend schema.
-- Client browsers never access these tables directly; Edge Functions use the service role.

create extension if not exists pgcrypto;

create table if not exists public.push_subscriptions (
  id uuid primary key default gen_random_uuid(),
  endpoint text not null unique,
  p256dh text not null,
  auth text not null,
  expiration_time timestamptz,
  preferences jsonb not null default '{}'::jsonb,
  timezone text not null default 'UTC',
  locale text not null default 'ar',
  enabled boolean not null default true,
  last_seen_at timestamptz not null default now(),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists push_subscriptions_enabled_idx
  on public.push_subscriptions (enabled)
  where enabled = true;

create table if not exists public.prayer_day_cache (
  city_id text not null,
  prayer_date date not null,
  timings jsonb not null,
  fetched_at timestamptz not null default now(),
  primary key (city_id, prayer_date)
);

create table if not exists public.push_delivery_log (
  id bigint generated by default as identity primary key,
  subscription_id uuid not null references public.push_subscriptions(id) on delete cascade,
  reminder_key text not null,
  reminder_date date not null,
  status text not null default 'sent' check (status in ('sent','failed')),
  http_status integer,
  error_message text,
  created_at timestamptz not null default now(),
  unique (subscription_id, reminder_key, reminder_date)
);

create index if not exists push_delivery_log_created_idx
  on public.push_delivery_log (created_at desc);

alter table public.push_subscriptions enable row level security;
alter table public.prayer_day_cache enable row level security;
alter table public.push_delivery_log enable row level security;

-- No public RLS policies are created intentionally. The Edge Functions use the
-- service role server-side, while anon/public clients can only call the
-- validated push-subscribe HTTP function.

create or replace function public.set_updated_at()
returns trigger
language plpgsql
security invoker
set search_path = ''
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists push_subscriptions_set_updated_at on public.push_subscriptions;
create trigger push_subscriptions_set_updated_at
before update on public.push_subscriptions
for each row execute function public.set_updated_at();
